#!/usr/bin/env python3
"""Gate for user_settings, profiles_deep and the users field rules.
Run: PB_BASE=... PB_TOKEN=<superuser> python3 verify_profiles.py"""
from vt_common import call, admin_token, Gate, Users

admin = admin_token()
g, users = Gate("profiles + settings + users rules"), Users(admin)
S = "/api/collections/user_settings/records"
D = "/api/collections/profiles_deep/records"
U = "/api/collections/users/records"
A, B, C = users.make("a"), users.make("b"), users.make("c")
made = []

# ---------------- user_settings
st, s = call("POST", S, {"user": A["id"], "accent_hue": 275, "show_attendance": True}, A["token"])
g.check("owner creates settings, hue 275 (positive control)", st == 200, f"{st} {s}")
sid = s.get("id")
made.append(f"{S}/{sid}")
st, _ = call("PATCH", f"{S}/{sid}", {"accent_hue": 120}, A["token"])
g.check("owner updates settings", st == 200, st)
st, _ = call("POST", S, {"user": B["id"], "accent_hue": 10}, A["token"])
g.rejected("cannot create settings for another user", st)
st, lst = call("GET", S, token=B["token"])
g.check("another member lists 0 settings", st == 200 and lst.get("totalItems") == 0, f"{st} {lst.get('totalItems')}")
st, _ = call("GET", f"{S}/{sid}", token=B["token"])
g.rejected("another member cannot view settings", st)
st, _ = call("PATCH", f"{S}/{sid}", {"accent_hue": 5}, B["token"])
g.rejected("another member cannot PATCH settings", st)
st, _ = call("DELETE", f"{S}/{sid}", token=B["token"])
g.rejected("another member cannot DELETE settings", st)
st, _ = call("PATCH", f"{S}/{sid}", {"user": B["id"]}, A["token"])
g.rejected("owner cannot re-point settings to another user", st)
st, lst = call("GET", S)
g.check("anonymous lists 0 settings", st in (200, 403) and not lst.get("items"), st)
# ("red;x" is cast to 0 by PocketBase before any hook runs: coerced, never stored raw; see uc_lib.js)
for label, v in (("99999", 99999), ("-5", -5), ("1e308", 1e308), ("12.5", 12.5)):
    st, _ = call("PATCH", f"{S}/{sid}", {"accent_hue": v}, A["token"])
    g.check(f"accent_hue {label} -> 400", st == 400, st)
st, r = call("PATCH", f"{S}/{sid}", {"accent_hue": "red;x"}, A["token"])
g.check("accent_hue 'red;x' is rejected or coerced to a number", st == 400 or (st == 200 and isinstance(r.get("accent_hue"), (int, float))), f"{st} {r.get('accent_hue')!r}")
st, r = call("PATCH", f"{S}/{sid}", {"accent_hue": 275}, A["token"])
g.check("accent_hue 275 ok (positive control)", st == 200 and r.get("accent_hue") == 275, st)
st, _ = call("POST", S, {"user": A["id"], "accent_hue": 1}, A["token"])
g.check("second settings row for same user -> 400", st == 400, st)

# ---------------- profiles_deep
body = {"user": A["id"], "experience": "Consultant 2019-2023", "skills": "python", "visibility": "members",
        "source": "self", "link_linkedin": "https://www.linkedin.com/in/x", "link_site": "https://example.org"}
st, p = call("POST", D, body, A["token"])
g.check("owner creates profile_deep with https links (positive control)", st == 200, f"{st} {p}")
pid = p.get("id")
made.append(f"{D}/{pid}")
st, lst = call("GET", D, token=B["token"])
g.check("another authed member lists the members-visible profile", st == 200 and any(i["id"] == pid for i in lst.get("items", [])), st)
st, _ = call("GET", f"{D}/{pid}", token=B["token"])
g.check("another authed member can view it by id", st == 200, st)
st, lst = call("GET", D)
g.check("anonymous lists 0 profiles", st in (200, 403) and not lst.get("items"), st)
st, _ = call("GET", f"{D}/{pid}")
g.rejected("anonymous cannot view a profile", st)
st, _ = call("PATCH", f"{D}/{pid}", {"visibility": "private"}, A["token"])
g.check("owner sets visibility private", st == 200, st)
st, lst = call("GET", D, token=B["token"])
g.check("private profile not listed for another member", st == 200 and not any(i["id"] == pid for i in lst.get("items", [])), st)
st, _ = call("GET", f"{D}/{pid}", token=B["token"])
g.rejected("private profile cannot be viewed by id", st)
st, _ = call("GET", f"{D}/{pid}", token=A["token"])
g.check("owner still sees private profile", st == 200, st)
call("PATCH", f"{D}/{pid}", {"visibility": "members"}, A["token"])

st, _ = call("POST", D, {"user": A["id"], "experience": "dup"}, A["token"])
g.check("second profile for same user -> 400", st == 400, st)
st, _ = call("POST", D, {"user": A["id"], "experience": "forged"}, B["token"])
g.rejected("non-owner cannot create a profile for A", st)
st, _ = call("PATCH", f"{D}/{pid}", {"experience": "pwned"}, B["token"])
g.rejected("non-owner cannot update", st)
st, _ = call("DELETE", f"{D}/{pid}", token=B["token"])
g.rejected("non-owner cannot delete", st)
st, _ = call("PATCH", f"{D}/{pid}", {"user": B["id"]}, A["token"])
g.rejected("user is immutable on update", st)
st, _ = call("PATCH", f"{D}/{pid}", {"is_sample": True}, A["token"])
g.rejected("member cannot set is_sample on update", st)
st, r = call("POST", D, {"user": B["id"], "is_sample": True, "experience": "x"}, B["token"])
g.rejected("member cannot set is_sample on create", st)
if st == 200:
    made.append(f"{D}/{r.get('id')}")
st, r = call("POST", D, {"user": B["id"], "experience": "B's own profile"}, B["token"])
g.check("B creates own profile without is_sample (positive control)", st == 200, st)
made.append(f"{D}/{r.get('id')}")
st, _ = call("GET", f"{D}/{r.get('id')}", token=B["token"])
for label, val in (("javascript: linkedin", "javascript:alert(1)"), ("data: linkedin", "data:text/html,x"), ("not a url", "hello")):
    st, _ = call("PATCH", f"{D}/{pid}", {"link_linkedin": val}, A["token"])
    g.check(f"link_linkedin {label} -> 400", st == 400, st)
st, _ = call("PATCH", f"{D}/{pid}", {"link_site": "javascript:alert(1)"}, A["token"])
g.check("link_site javascript: -> 400", st == 400, st)
st, _ = call("PATCH", f"{D}/{pid}", {"link_linkedin": "https://www.linkedin.com/in/x"}, A["token"])
g.check("link_linkedin https ok (positive control)", st == 200, st)
for field, mx in (("experience", 2000), ("education", 1000), ("skills", 500), ("sectors", 300), ("languages", 200),
                  ("offer", 500), ("seek", 500), ("source", 20), ("visibility", 10)):
    st, _ = call("PATCH", f"{D}/{pid}", {field: "x" * (mx + 1)}, A["token"])
    g.check(f"{field} > {mx} chars -> 400", st == 400, st)
st, _ = call("PATCH", f"{D}/{pid}", {"experience": "x" * 2000}, A["token"])
g.check("experience exactly 2000 chars ok (positive control)", st == 200, st)
st, _ = call("PATCH", f"{D}/{pid}", {"visibility": "public"}, A["token"])
g.check("visibility outside members|private -> 400", st == 400, st)
st, _ = call("PATCH", f"{D}/{pid}", {"source": "gemini_scraped"}, A["token"])
g.check("source outside self|linkedin_import|sample -> 400", st == 400, st)

# ---------------- users field rules
for mode in ("open", "points", "request", "closed"):
    st, _ = call("PATCH", f"{U}/{A['id']}", {"contact_mode": mode}, A["token"])
    g.check(f"contact_mode {mode} ok", st == 200, st)
st, _ = call("PATCH", f"{U}/{A['id']}", {"contact_mode": "admin"}, A["token"])
g.rejected("contact_mode admin rejected (rule failure)", st)
st, _ = call("PATCH", f"{U}/{A['id']}", {"min_points": 50}, A["token"])
g.check("min_points 50 ok", st == 200, st)
for v in (-1, 99999):
    st, _ = call("PATCH", f"{U}/{A['id']}", {"min_points": v}, A["token"])
    g.check(f"min_points {v} -> 400", st == 400, st)
st, _ = call("PATCH", f"{U}/{A['id']}", {"role": "admin"}, A["token"])
g.rejected("role admin rejected (rule failure)", st)
for r_ in ("alumnus", "student", "staff"):
    st, _ = call("PATCH", f"{U}/{A['id']}", {"role": r_}, A["token"])
    g.check(f"role {r_} ok", st == 200, st)
st, _ = call("PATCH", f"{U}/{A['id']}", {"points": 5000}, A["token"])
g.rejected("points self-edit rejected", st)
st, _ = call("PATCH", f"{U}/{A['id']}", {"supporter": True}, A["token"])
g.rejected("supporter self-edit rejected", st)
st, _ = call("PATCH", f"{U}/{A['id']}", {"headline": "Analyst"}, A["token"])
g.check("headline self-edit ok (positive control)", st == 200, st)
st, ua = call("GET", f"{U}/{A['id']}", token=A["token"])
g.check("points still 0 after attempts", not ua.get("points"), ua.get("points"))
st, _ = call("PATCH", f"{U}/{A['id']}", {"headline": "hijack"}, B["token"])
g.rejected("another member cannot edit A's users record", st)
st, _ = call("PATCH", f"{U}/{A['id']}", {"verified": True}, A["token"])
g.check("member cannot self-set verified (NOTE: verified gates map+events)", st in (400, 403, 404), st)
st, _ = call("PATCH", f"{U}/{A['id']}", {"email": "x_" + A["id"] + "@example.test"}, A["token"])
st, _ = call("DELETE", f"{U}/{C['id']}", token=B["token"])
g.rejected("another member cannot delete a users record", st)

# email visibility + listRule
st, ub = call("GET", f"{U}/{A['id']}", token=B["token"])
g.check("another member can view users record (positive control)", st == 200 and ub.get("id") == A["id"], st)
g.check("another member's view exposes no email", not ub.get("email"), ub.get("email"))
st, lst = call("GET", U + "?perPage=100", token=B["token"])
g.check("list exposes no email for others", st == 200 and all(not i.get("email") for i in lst["items"] if i["id"] != B["id"]), st)
st, own = call("GET", f"{U}/{B['id']}", token=B["token"])
g.check("a member sees own email (positive control)", bool(own.get("email")), own.get("email"))
st, lst = call("GET", U)
g.check("anonymous lists 0 users", st in (200, 403) and not lst.get("items"), st)
st, _ = call("GET", f"{U}/{A['id']}")
g.rejected("anonymous cannot view a user", st)

users.cleanup(made)
g.done()
